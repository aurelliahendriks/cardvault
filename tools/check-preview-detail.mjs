import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1560, height: 1150 }, deviceScaleFactor: 1.3 });
const errs = [];
p.on('pageerror', (e) => errs.push('PAGEERROR: ' + e.message));
await p.goto('file:///home/claude/cardvault/cardvault-preview.html', { waitUntil: 'load' });
await p.waitForTimeout(2500);
await p.click('#modeSeg button[data-k="cards"]');
await p.waitForTimeout(1500);
await p.locator('.card').first().click();
await p.waitForTimeout(1600);
const meters = (await p.locator('dialog#dlg .num').allInnerTexts()).filter((t) => /\/100|not assessed/.test(t));
console.log('meters in the offline preview:', meters.map((s) => s.trim()).join('  |  '));
await p.locator('dialog#dlg .dlg > div').first().screenshot({ path: '/tmp/shots/pv-scores.png' });
await p.click('#dlgX'); await p.waitForTimeout(400);
await p.click('nav button[data-t="data"]');
await p.waitForTimeout(1500);
const ch = await p.locator('#clubHealth').innerText();
console.log('club health panel:', ch.replace(/\n+/g, ' | ').slice(0, 190));
await p.locator('#clubHealth').screenshot({ path: '/tmp/shots/pv-clubhealth.png' });
const sh = await p.locator('#shadowHealth').innerText();
console.log('calibration panel:', sh.replace(/\n+/g, ' | ').slice(0, 200));
console.log('ERRORS:', errs.length ? errs.slice(0, 4) : 'none');
await b.close();
